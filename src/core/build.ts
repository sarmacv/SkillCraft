// Multi-target build: one skill source → a ready-to-install folder per tool,
// each customized for that tool, plus README.md, SETUP.md and install scripts.

import * as fs from 'node:fs';
import * as path from 'node:path';
import { stringify as stringifyYaml } from 'yaml';
import { scriptEnvVars, scriptImports } from './checks';
import { BEGIN, END, renderWorkflowSection, workflowFor } from './codegen/generate';
import { allEnvVars, installPs1, installSh, readme, setup } from './docs';
import { commonFrontmatter, PROFILES } from './profiles';
import { DIST_DIR, type Workspace } from './project';
import { joinFrontmatter, loadSkill } from './skill';
import type { TargetId } from './types';

export interface TargetBuild {
  target: TargetId | 'universal';
  dir: string;
  files: string[];
  warnings: string[];
}

export interface BuildResult {
  ok: boolean;
  outDir: string;
  builds: TargetBuild[];
  errors: string[];
}

const PY_STDLIB_HINT = new Set(['os', 'sys', 'json', 're', 'urllib', 'argparse', 'glob', 'shlex', 'subprocess', 'base64', 'datetime', 'pathlib', 'csv', 'collections', 'typing', 'time', 'math', 'smtplib', 'email', 'sqlite3', 'itertools', 'functools', 'random', 'hashlib', 'tempfile', 'shutil', 'io', 'textwrap', 'dataclasses', 'logging', 'string', 'uuid']);

function writeFile(abs: string, content: string | Buffer, mode?: number): void {
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content);
  if (mode) fs.chmodSync(abs, mode);
}

function listFiles(dir: string, base = dir): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const abs = path.join(dir, e.name);
    return e.isDirectory() ? listFiles(abs, base) : [path.relative(base, abs).split(path.sep).join('/')];
  });
}

function codexYaml(ws: Workspace, description: string, target: TargetId): string | undefined {
  const wf = workflowFor(ws.workflow, target);
  const tools = wf.nodes
    .filter((n) => n.type === 'source.mcp' || n.type === 'output.mcp')
    .map((n) => ({ type: 'mcp', value: String(n.config.server ?? ''), description: `${n.label}: ${String(n.config.tool ?? '')}`.trim(), ...(n.config.url ? { transport: 'streamable_http', url: String(n.config.url) } : {}) }))
    .filter((t) => t.value);
  const doc = {
    interface: { display_name: ws.config.name.replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase()), short_description: description.split('. ')[0].slice(0, 120) },
    ...(tools.length ? { dependencies: { tools } } : {}),
  };
  return `# Generated by SkillCraft for OpenAI Codex.\n${stringifyYaml(doc)}`;
}

export function build(ws: Workspace, opts: { targets?: TargetId[] } = {}): BuildResult {
  const targets = opts.targets?.length ? opts.targets : ws.config.targets;
  const skillAbs = path.join(ws.root, ws.config.skillPath);
  const skill = loadSkill(skillAbs);
  const outDir = path.join(ws.root, DIST_DIR);
  const errors: string[] = [];
  const name = ws.config.name;

  if (!skill.skillMd?.frontmatter) errors.push('SKILL.md is missing or has invalid frontmatter.');
  if (skill.folderName !== name) errors.push(`Skill folder "${skill.folderName}" must match the project name "${name}".`);
  if (errors.length) return { ok: false, outDir, builds: [], errors };

  fs.rmSync(outDir, { recursive: true, force: true });
  const fm = skill.skillMd!.frontmatter!;
  const sourceDescription = String(fm.description ?? '');

  // Facts for the docs.
  const envFromScripts = new Set<string>();
  const pyDeps = new Set<string>();
  let nodeDeps = false;
  for (const f of skill.files) {
    const lang = f.rel.endsWith('.py') ? 'python' : /\.(m?js|cjs|ts)$/.test(f.rel) ? 'node' : f.rel.endsWith('.sh') ? 'bash' : '';
    if (!lang || f.text === undefined) continue;
    scriptEnvVars(f.text, lang).forEach((v) => envFromScripts.add(v));
    if (lang === 'python') scriptImports(f.text, lang).filter((m) => !PY_STDLIB_HINT.has(m)).forEach((m) => pyDeps.add(m));
  }
  const reqs = skill.files.find((f) => f.rel === 'scripts/requirements.txt')?.text;
  const pythonDeps = reqs ? reqs.split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#')) : [];
  nodeDeps = skill.files.some((f) => f.rel === 'scripts/package.json');
  const read = (rel: string) => {
    try {
      return fs.readFileSync(path.join(ws.root, rel), 'utf8');
    } catch {
      return undefined;
    }
  };

  const universal = ws.config.buildMode === 'universal';
  const plans: (TargetId | 'universal')[] = universal ? ['universal'] : targets;
  const builds: TargetBuild[] = [];

  for (const plan of plans) {
    const warnings: string[] = [];
    const t: TargetId | undefined = plan === 'universal' ? undefined : plan;
    const override = t ? ws.config.overrides?.[t] : undefined;
    const allowed = new Set(t ? PROFILES[t].frontmatter.supported : commonFrontmatter(targets));
    const merged: Record<string, unknown> = { ...fm, ...(override?.frontmatter ?? {}) };
    if (override?.description) merged.description = override.description;
    const kept: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(merged)) {
      if (allowed.has(k)) kept[k] = v;
      else warnings.push(`Dropped frontmatter field "${k}" — ${t ? PROFILES[t].displayName : 'not every target'} doesn't support it.`);
    }
    kept.name = name;
    const limit = t ? PROFILES[t].limits.descriptionChars : Math.min(...targets.map((x) => PROFILES[x].limits.descriptionChars));
    if (String(kept.description ?? '').length > limit) warnings.push(`Description is longer than ${limit} characters and may be truncated.`);

    let body = skill.skillMd!.body;
    if (body.includes(BEGIN) && body.includes(END) && ws.workflow.nodes.length) {
      const section = renderWorkflowSection(workflowFor(ws.workflow, t), ws.config.language);
      body = body.slice(0, body.indexOf(BEGIN)) + section + body.slice(body.indexOf(END) + END.length);
    }
    body = body.replace(/\n{3,}/g, '\n\n');
    if (override?.extraInstructions?.trim()) body = `${body.trimEnd()}\n\n${override.extraInstructions.trim()}\n`;

    const targetDir = path.join(outDir, plan);
    const skillOut = path.join(targetDir, name);
    const files: string[] = [];
    for (const f of skill.files) {
      if (f.rel === 'SKILL.md') continue;
      const src = path.join(skillAbs, f.rel);
      writeFile(path.join(skillOut, f.rel), fs.readFileSync(src), f.rel.startsWith('scripts/') && /\.(py|sh|mjs|js)$/.test(f.rel) ? 0o755 : undefined);
      files.push(`${name}/${f.rel}`);
    }
    writeFile(path.join(skillOut, 'SKILL.md'), joinFrontmatter(kept, body));
    files.push(`${name}/SKILL.md`);

    // Tool-specific extras and per-tool file overlays (overrides/<target>/files/**).
    const extraTargets = t ? [t] : targets;
    if (extraTargets.includes('codex')) {
      const yaml = codexYaml(ws, String(kept.description ?? ''), 'codex');
      if (yaml && !skill.files.some((f) => f.rel === 'agents/openai.yaml')) {
        writeFile(path.join(skillOut, 'agents', 'openai.yaml'), yaml);
        files.push(`${name}/agents/openai.yaml`);
      }
    }
    if (t) {
      const overlay = path.join(ws.root, 'overrides', t, 'files');
      for (const rel of listFiles(overlay)) {
        writeFile(path.join(skillOut, rel), fs.readFileSync(path.join(overlay, rel)));
        if (!files.includes(`${name}/${rel}`)) files.push(`${name}/${rel}`);
        warnings.push(`Used ${t}-specific ${rel} from overrides/${t}/files.`);
      }
    }

    const docInputs = {
      config: ws.config,
      workflow: workflowFor(ws.workflow, t),
      description: String(kept.description ?? sourceDescription),
      envVars: allEnvVars(ws.workflow, [...envFromScripts]),
      pythonDeps: pythonDeps.length ? pythonDeps : [...pyDeps],
      nodeDeps,
      setupNotes: Object.fromEntries(targets.map((x) => [x, read(`docs/setup-${x}.md`)])) as Partial<Record<TargetId, string>>,
      testResults: ws.state.testResults,
      builtTargets: targets,
      universal,
    };
    writeFile(path.join(targetDir, 'SETUP.md'), setup(docInputs, plan));
    writeFile(path.join(targetDir, 'install.sh'), installSh(name, t ? [t] : targets), 0o755);
    writeFile(path.join(targetDir, 'install.ps1'), installPs1(name, t ? [t] : targets));
    files.push('SETUP.md', 'install.sh', 'install.ps1');
    builds.push({ target: plan, dir: targetDir, files, warnings });
  }

  writeFile(
    path.join(outDir, 'README.md'),
    readme({
      config: ws.config,
      workflow: ws.workflow,
      description: sourceDescription,
      envVars: allEnvVars(ws.workflow, [...envFromScripts]),
      pythonDeps: pythonDeps.length ? pythonDeps : [...pyDeps],
      nodeDeps,
      notes: read('docs/notes.md'),
      testResults: ws.state.testResults,
      builtTargets: targets,
      universal,
    }),
  );
  writeFile(path.join(outDir, 'build-report.json'), JSON.stringify({ at: new Date().toISOString(), name, version: ws.config.version, mode: ws.config.buildMode, builds: builds.map((b) => ({ target: b.target, files: b.files, warnings: b.warnings })) }, null, 2) + '\n');
  return { ok: true, outDir, builds, errors };
}
